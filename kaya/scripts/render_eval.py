"""Render docs/EVAL.md from the recorded result files so no number is transcribed by hand."""
from __future__ import annotations

import json
from pathlib import Path

R = Path(__file__).resolve().parent.parent / "eval" / "results"


def load(name: str) -> dict:
    return json.loads((R / name).read_text(encoding="utf-8"))


def table(run: dict) -> str:
    rows = ["| Package | Fields | Findings (extra) | Decision checks | Revision checks |", "| --- | --- | --- | --- | --- |"]
    for r in run["results"]:
        f, fi, d, rev = r["fields"], r["findings"], r["decision"], r.get("revision")
        rows.append(f"| {r['package']} | {f['correct']}/{f['total']} | {fi['correct']}/{fi['expected']} (+{len(fi['false_positive_findings'])}) | {d['passed']}/{d['total']} | "
                    + (f"{rev['passed']}/{rev['total']}" if rev else "n/a") + " |")
    s = run["summary"]
    rows.append(f"| **all** | **{s['fields_correct']}** | **{s['findings_correct']}** (+{s['false_positive_findings']}) | **{s['decision_checks_passed']}** | **{s['revision_checks_passed']}** |")
    return "\n".join(rows)


def misses(run: dict) -> str:
    out = []
    for r in run["results"]:
        lines = []
        for m in r["fields"]["misses"]:
            exp = m["expected"]
            e = exp["status"] + (f" {exp['value']}" if "value" in exp and exp["value"] is not None else "")
            g = m["got"]["status"] + (f" {m['got']['value']}" if m["got"].get("value") is not None else "")
            lines.append(f"  * field `{m['role']}.{m['field']}`: expected {e}; got {g}")
        for w in r["findings"]["wrong"]:
            lines.append(f"  * finding `{w['key']}`: expected {w['expected']}; got {w['got']}")
        for k in r["findings"]["false_positive_findings"]:
            lines.append(f"  * unexpected finding `{k}`")
        for k, ok in r["decision"]["checks"].items():
            if not ok:
                lines.append(f"  * decision check failed: {k}")
        if r.get("revision"):
            for k, ok in r["revision"]["checks"].items():
                if not ok:
                    lines.append(f"  * revision check failed: {k}")
        if lines:
            out.append(f"* **{r['package']}**\n" + "\n".join(lines))
    return "\n".join(out) or "* none"


